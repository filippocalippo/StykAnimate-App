/** Build the ordinary 2D starter with the editor's native IK setup.
 * Run from the repository root. No rig setup runs during startup. */
import {writeFile} from 'node:fs/promises';
import {defaultFigure,emptyDocument,createFrame,createObject} from '../src/demo.mjs';
import {Editor} from '../src/editor.mjs';
import {syncDerived} from '../src/pivot/model.mjs';
import {loadEngine} from '../src/engine/engine.mjs';
import {useEngine} from '../src/engine/engine-open.mjs';
import {installEngineOwner} from '../src/engine/engine-owner.mjs';

const figure=defaultFigure();figure.name='Blue';
const names=['Torso','Head','Left upper arm','Left forearm','Right upper arm','Right forearm',
  'Left thigh','Left lower leg','Right thigh','Right lower leg'];
const thickness=[16,0,12,12,12,12,14,14,14,14];
for(const [i,segment]of figure.segments.entries())
  Object.assign(segment,{name:names[i],thickness:thickness[i],color_rgb:[13,153,255]});
Object.assign(figure.segments[1],{primitive_code:3,flags:3,segment_kind:'circleFill'});
// Mirror the limbs with separated handles and a slight elbow/knee bend.
// Native angles are absolute; the four two-bone chains never share a bone.
for(const [left,right]of [[2,4],[3,5],[6,8],[7,9]])
  figure.segments[right].angle_rad=Math.PI-figure.segments[left].angle_rad;
const report=emptyDocument();report.figure_types=[figure];
report.keyframes=[createFrame([createObject(figure,1,480,280)])];
// The engine edits the document: the IK controllers are its command (setNodeIK).
useEngine(await loadEngine({workers:0}));
const editor=new Editor({demo:false,layerTimeline:true,propertyChannels:true});editor.load(report);
const owner=installEngineOwner(editor);
for(const name of ['Left forearm','Right forearm','Left lower leg','Right lower leg']){
  editor.select(1,figure.segments.findIndex(s=>s.name===name));
  editor.setNodeIK({enabled:true,pinned:false,chainLength:2,bendDirection:0});
}
// The pose is the first frame of the figure's layer, which is where the session wrote the controllers.
const document=editor.serialize(),frame=document._styk.frameSources[editor.layerFrameKeys(editor.layerForUid(1))[0].value.frameId];
syncDerived({...document,keyframes:[frame]});
const asset={figure:editor.figure,object:frame.objects[0]};
owner.release();
await writeFile(new URL('../src/startup-blue-data.mjs',import.meta.url),
  '// Generated by scripts/build-startup-blue.mjs: ordinary 2D lines, a circle and four IK chains.\n'+
  '// A fresh literal keeps each new document independent; IK setup is offline.\n'+
  `export function createBlueStartupPose(){return ${JSON.stringify(asset)};}\n`);
console.log(`Blue startup asset: ${figure.segments.length} joints, four 2D IK chains.`);
