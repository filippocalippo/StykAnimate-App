import { readFile, writeFile, readdir } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { parsePivotLanguage, mapPivotCaptions, PIVOT_CAPTION_KEYS, PIVOT_LOCALE_KEY_OVERRIDES } from '../src/locales/pivot-language.mjs';

const root = fileURLToPath(new URL('../', import.meta.url));
const directory = path.resolve(process.argv[2] || path.join(root, '../Pivot Animator v5/languages'));
// BOM is authoritative. Legacy code pages are explicit by supplied language,
// never the build machine's locale or byte-preserving Latin-1.
const languages = [
  ['en','English','English','English.ini',1252],
  ['ar','Arabic','العربية','Arabic.ini',1252,'rtl'],
  ['zh-Hans','Chinese (Simplified)','简体中文','Chinese.ini',1252],
  ['hr','Croatian','Hrvatski','Croatian.ini',1250],
  ['cs','Czech','Čeština','Czech.ini',1250],
  ['da','Danish','Dansk','Dansk.ini',1252],
  ['nl','Dutch','Nederlands','Dutch.ini',1252],
  ['fi','Finnish','Suomi','Finnish.ini',1252],
  ['fr','French','Français','Francais.ini',1252],
  ['de','German','Deutsch','Deutsch.ini',1252],
  ['el','Greek','Ελληνικά','Greek.ini',1252],
  ['he','Hebrew','עברית','Hebrew.ini',1252,'rtl'],
  ['hu','Hungarian','Magyar','Hungarian.ini',1250],
  ['id','Indonesian','Bahasa Indonesia','Indonesian.ini',1252],
  ['it','Italian','Italiano','Italiano.ini',1252],
  ['kk','Kazakh','Қазақша','Kazakh.ini',1251],
  ['nb','Norwegian Bokmål','Norsk bokmål','Norwegian.ini',1252],
  ['pl','Polish','Polski','Polski.ini',1250],
  ['pt-BR','Portuguese (Brazil)','Português (Brasil)','Portuguese-BR.ini',1252],
  ['ro','Romanian','Română','Romana.ini',1250],
  ['ru','Russian','Русский','Russian.ini',1251],
  ['sl','Slovenian','Slovenščina','Slovensko.ini',1250],
  ['es','Spanish','Español','Espanol.ini',1252],
  ['es-419','Spanish (Latin America)','Español (Latinoamérica)','Espanol_Latino.ini',1252],
  ['tr','Turkish','Türkçe','Turkish.ini',1254],
  ['uk','Ukrainian','Українська','Ukrainian.ini',1251],
  ['vi','Vietnamese','Tiếng Việt','Vietnamese.ini',1252],
];
const supplied = (await readdir(directory)).filter(file => file.endsWith('.ini')).sort();
if (JSON.stringify(supplied) !== JSON.stringify(languages.map(item => item[3]).sort())) throw new Error('Supplied language inventory changed; review the explicit metadata.');
const english = parsePivotLanguage(await readFile(path.join(directory,'English.ini')));
const catalogs = {}, metadata = [], files = [];
for (const [id,name,nativeName,file,codepage,direction='ltr'] of languages) {
  const bytes = await readFile(path.join(directory,file));
  const legacyEncoding = `windows-${codepage}`;
  const entries = parsePivotLanguage(bytes,{legacyEncoding});
  const catalog = mapPivotCaptions(entries,english,{locale:id});
  catalogs[id] = catalog;
  metadata.push({id,name,nativeName,direction,coverage:['en','it'].includes(id)?'common-controls':'native-captions',source:file,mappedKeys:Object.keys(catalog).length});
  const encoding = bytes[0] === 255 && bytes[1] === 254 ? 'UTF-16LE BOM' : bytes[0] === 254 && bytes[1] === 255 ? 'UTF-16BE BOM' : bytes[0] === 239 && bytes[1] === 187 ? 'UTF-8 BOM' : legacyEncoding;
  files.push({file,locale:id,bytes:bytes.length,sha256:createHash('sha256').update(bytes).digest('hex'),encoding,keys:Object.keys(entries).length,missingEnglishKeys:Object.keys(english).filter(key=>!Object.hasOwn(entries,key)).length,sameAsEnglish:Object.keys(english).filter(key=>entries[key]===english[key]).length,mappedAppKeys:Object.keys(catalog).length,samples:Object.fromEntries(['MPlayCap','OLangBox','BSave','CancelBitCap'].map(key=>[key,entries[key]??null]))});
}
const generated = `// Generated by scripts/build-native-locales.mjs from supplied Pivot 5.2.11 INI data.\n// Partial captions only; modern app text falls back to its English catalog.\nconst metadata = ${JSON.stringify(metadata,null,2)};\nconst catalogs = ${JSON.stringify(catalogs,null,2)};\nexport const NATIVE_LOCALES = Object.freeze(metadata.map(Object.freeze));\nexport default Object.freeze(Object.fromEntries(Object.entries(catalogs).map(([id,entries])=>[id,Object.freeze(entries)])));\n`;
await writeFile(path.join(root,'src/locales/native-catalogs.mjs'),generated,'utf8');
await writeFile(path.join(root,'artifacts/localization-native-inventory.json'),JSON.stringify({baseline:'Pivot Animator 5.2.11 supplied local language files',languageFileCount:languages.length,englishKeys:Object.keys(english).length,semanticCaptionMappings:PIVOT_CAPTION_KEYS,reviewedSourceExceptions:PIVOT_LOCALE_KEY_OVERRIDES,files},null,2)+'\n','utf8');
console.log(`Generated ${languages.length} locale catalogs from ${files.reduce((sum,file)=>sum+file.bytes,0)} supplied bytes; ${generated.length} generated characters.`);
