import { mkdir, readdir, readFile, rm, writeFile } from 'node:fs/promises';
import english from '../src/locales/en.mjs';
import {diagnosticError} from '../src/message-error-core.mjs';
import {inspectApplicationMessages} from './localization-source.mjs';
import { validateCatalog, parseLanguagePack } from '../src/locales/catalog-validation.mjs';

const check = process.argv.includes('--check'), strict = process.argv.includes('--strict');
const localeIndex = process.argv.indexOf('--locale');
const requested = localeIndex === -1 ? null : process.argv[localeIndex + 1];
const validateOnly = process.argv.includes('--validate-only') || localeIndex !== -1;
if (localeIndex !== -1 && (!requested || requested.startsWith('--'))) throw new Error('Supply a locale ID after --locale.');
const source = await inspectApplicationMessages(english);
const packs = [], errors = [...source.errors], ids = new Set(), aliases = new Set();
console.log(`${source.references} source message references checked.`);
errors.push(...validateCatalog({locale: {id: 'en', name: 'English', nativeName: 'English', direction: 'ltr'}, messages: english}, english).errors.map(error => `English: ${error}`));
const files = (await readdir('src/locales/packs')).filter(file => file.endsWith('.json') && (!requested || file === `${requested}.json`)).sort();
if (!files.length) errors.push(`No language pack matches ${requested}.`);
for (const file of files) {
  let pack;
  try { pack = parseLanguagePack(await readFile(`src/locales/packs/${file}`, 'utf8')); }
  catch (error) { errors.push(`${file}: ${error.message}`); continue; }
  const report = validateCatalog(pack, english);
  if (!pack?.locale?.id) { errors.push(`${file}: missing locale metadata`); continue; }
  if (file !== `${pack.locale.id}.json` || ids.has(pack.locale.id)) errors.push(`${file}: duplicate or mismatched ID`);
  ids.add(pack.locale.id);
  for (const alias of Array.isArray(pack.locale.aliases) ? pack.locale.aliases : []) {
    if (aliases.has(alias)) errors.push(`${file}: duplicate alias ${alias}`);
    aliases.add(alias);
  }
  errors.push(...report.errors.map(error => `${file}: ${error}`));
  for (const item of report.incompletePlurals) {
    const warning = `${file}: ${item.key} lacks ${item.forms.join(', ')}; those forms use English fallback`;
    if (strict) errors.push(warning); else console.warn(warning);
  }
  if (strict && pack.locale.id !== 'en' && report.missing.length) errors.push(`${file}: ${report.missing.length} untranslated messages`);
  console.log(`${pack.locale.id}: ${pack.locale.id === 'en' ? Object.keys(english).length : Object.keys(pack.messages ?? {}).length}/${Object.keys(english).length} messages; ${pack.locale.id === 'en' ? 0 : report.missing.length} use English fallback`);
  packs.push(pack);
}
for (const alias of aliases) if (ids.has(alias)) errors.push(`Alias ${alias} shadows a locale ID`);
if (errors.length) { console.error(errors.join('\n')); process.exitCode = 1; }
else if (!validateOnly) {
  const preloadPath = 'desktop/preload.cjs';
  const preload = await readFile(preloadPath, 'utf8');
  const preloadKeys = [...new Set([...preload.matchAll(/messageError\([^\n]*?['"](desktop\.preload\.errors\.[A-Za-z0-9.]+)['"]/g)].map(match => match[1]))];
  const diagnostics = Object.fromEntries(preloadKeys.map(key => [key, english[key]]));
  const bundle = '// BEGIN generated localization diagnostics\n' +
    'const diagnosticEnglish = ' + JSON.stringify(diagnostics, null, 2) + ';\n' +
    diagnosticError.toString() + '\n' +
    'const messageError = (error, key, params) => diagnosticError(error, diagnosticEnglish[key], key, params);\n' +
    '// END generated localization diagnostics';
  const bundledPreload = preload.replace(/\/\/ BEGIN generated localization diagnostics[\s\S]*?\/\/ END generated localization diagnostics/, bundle);
  if (check) { if (preload !== bundledPreload) { console.error('Preload diagnostics are stale. Run npm run locales:build.'); process.exitCode = 1; } }
  else await writeFile(preloadPath, bundledPreload);
  // Bundling the constructor can shift preload line numbers. Review locations
  // describe the generated bytes, so one build must also pass the next check.
  const contextSource = !check && preload !== bundledPreload ? await inspectApplicationMessages(english) : source;
  const context = JSON.stringify(Object.fromEntries(Object.entries(contextSource.contexts).map(([key, uses]) => [key, {locations: uses.map(({file, line}) => `${file}:${line}`), context: uses[0].context.slice(0, 160)}])), null, 2) + '\n';
  const contextTarget = 'docs/localization-message-context.json';
  if (check) { if (await readFile(contextTarget, 'utf8').catch(() => '') !== context) { console.error('Generated message context is stale. Run npm run locales:build.'); process.exitCode = 1; } }
  else await writeFile(contextTarget, context);
  // The registry is the list of languages; each language's messages are a module of their own that a session loads
  // when it needs the language (src/localization.mjs). English comes from the feature catalogs, not from a pack.
  const generated = new Map([['src/locales/locale-index.mjs', `// Generated by npm run locales:build. Edit packs/*.json, then regenerate.
const locales = ${JSON.stringify(packs.map(pack => pack.locale), null, 2)};
for (const locale of locales) {
  if (locale.aliases) Object.freeze(locale.aliases);
  Object.freeze(locale);
}
export default Object.freeze(locales);
`]]);
  for (const pack of packs) if (pack.locale.id !== 'en') generated.set(`src/locales/messages/${pack.locale.id}.mjs`,
    `// Generated by npm run locales:build. Edit packs/${pack.locale.id}.json, then regenerate.
const messages = ${JSON.stringify(pack.messages, null, 2)};
for (const message of Object.values(messages)) if (typeof message === 'object') Object.freeze(message);
export default Object.freeze(messages);
`);
  const stale = (await readdir('src/locales/messages').catch(() => [])).map(name => `src/locales/messages/${name}`).filter(name => !generated.has(name));
  for (const [target, data] of generated) {
    if (check) { if (await readFile(target, 'utf8').catch(() => '') !== data) { console.error(`${target} is stale. Run npm run locales:build.`); process.exitCode = 1; } }
    else { await mkdir('src/locales/messages', { recursive: true }); await writeFile(target, data); }
  }
  for (const target of stale) {
    if (check) { console.error(`${target} has no language pack. Run npm run locales:build.`); process.exitCode = 1; }
    else await rm(target);
  }
}
