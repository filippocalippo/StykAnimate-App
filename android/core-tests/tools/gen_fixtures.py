"""Builds native_fixtures.h (container test vectors) with the project's own encoder.

Usage: python3 gen_fixtures.py <output header>
"""
import base64, json, sys, os
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import native_ref as nr


def blob(n, seed):
    return bytes((i * seed + (i >> 5)) % 251 for i in range(n))


shared = [(i * 7) % 256 for i in range(40)]           # u8, used twice (identity)
doc_a = {"fps": 24, "name": "ação €", "layers": [{"id": 1, "visible": True}, {"id": 2, "visible": False}],
         "scale": 1.5, "note": None, "figure_types": [], "keyframes": [{"objects": [], "duration": 3}]}

png = blob(60000, 3)
raw2 = blob(55000, 5)
doc_b = {
    "fps": 30,
    "poses": {"a": shared, "b": shared},
    "u16": [i * 300 for i in range(50)],
    "u32": [4000000000 + i for i in range(40)],
    "i32": [-5 - i for i in range(33)],
    "f32": [0.5 * i for i in range(35)],
    "f64": [0.1 * i for i in range(36)],
    "mixed_small": [1, 2.5, 3],                       # below the lift threshold
    "label": "S2B:u8:0:0:1",                          # literal that looks like a marker
    "escaped_e": "S2E:already",
    "images": [
        {"data_base64": base64.b64encode(png).decode()},
        {"data_url": "data:image/png;base64," + base64.b64encode(raw2).decode()},
        {"data_base64": base64.b64encode(png).decode()},  # duplicate payload
    ],
    "text": "Olá, мир 😀",
    "figure_types": [{"figure_type_id": 2, "name": "stick", "angles": [0.25] * 32}],
    "keyframes": [],
}
wrapped = {"format": "stykanimate", "version": 1,
           "document": {"fps": 12, "editable_paths": [1], "_codec": "x", "kept": 1}}


def js(o):
    return json.dumps(o, ensure_ascii=False, separators=(',', ':'))


out = {}
out['v1'] = nr.encode(js(doc_a).encode('utf-8'), 'styk')
out['v2'] = nr.encode_v2(doc_b, 'styk')
out['v2_stkz'] = nr.encode_v2(doc_a, 'stkz')
out['plain'] = ('\ufeff ' + js(doc_a)).encode('utf-8')
out['wrapped'] = js(wrapped).encode('utf-8')


def hexarr(name, data):
    lines = []
    for i in range(0, len(data), 24):
        lines.append('    ' + ','.join('0x%02x' % b for b in data[i:i + 24]) + ',')
    return 'static const unsigned char %s[] = {\n%s\n};\nstatic const size_t %s_size = %d;\n' % (
        name, '\n'.join(lines), name, len(data))


def strc(name, text):
    return hexarr(name, text.encode('utf-8'))


parts = ["// Generated by tools/gen_fixtures.py from the project's own encoder. Do not edit.\n"
         "#pragma once\n#include <cstddef>\n"]
for k, v in out.items():
    parts.append(hexarr('kFixture_' + k, v))
parts.append(strc('kExpected_a', js(doc_a)))
parts.append(strc('kExpected_b', js({k: v for k, v in doc_b.items() if k != 'images'})))
parts.append(strc('kExpected_wrapped', js({"fps": 12, "kept": 1})))
with open(sys.argv[1], 'w') as f:
    f.write('\n'.join(parts))
