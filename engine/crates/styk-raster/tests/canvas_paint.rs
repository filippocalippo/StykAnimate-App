//! Actual Editor/Canvas monitor pixels, including fractional corners and
//! independent translucent paints. Fixture JSON is read at runtime.
use std::path::Path;
use styk_eval::{assets::Assets, drawlist, geometry};
use styk_raster::{Edges, Images, Raster, ViewParams, PaintContext};

#[test]
fn editor_camera_rotation_selects_path_before_corner_rounding() {
    let at = Path::new(env!("CARGO_MANIFEST_DIR")).join("tests/fixtures/canvas-paint");
    for name in ["background-tiny-camera","background-negative-tiny-camera"] {
        let prepared = styk_eval::prepare(styk_eval::open(&at.join(format!("{name}.json"))).unwrap());
        let frame = prepared.evaluate(0.0);
        let matrix = styk_eval::view::camera_matrix(&prepared.doc,frame.camera.as_ref(),0.139,[69.5,0.0]);
        let bounds = styk_eval::view::background_bounds(&prepared.doc,frame.camera.as_ref(),true,[0.0,0.0,1000.0,1000.0]).rect;
        let paint = styk_render::paint::PaintQuad::rectangle(matrix,bounds);
        let q = paint.0.map(|p|p.map(|v|v as f32));
        assert_eq!((q[0][1],q[1][0],q[2][1],q[3][0]),(q[1][1],q[2][0],q[3][1],q[0][0]),"recorded tiny-camera corners round to an axis-aligned rectangle");
        assert_eq!(paint.canvas_alpha(matrix,[69,0]),None,"the actual Canvas painter still classifies the nonzero original matrix skew as a path");
    }
}

#[test]
fn recorded_canvas_clip_applies_at_each_root_paint_including_corners() {
    let at = Path::new(env!("CARGO_MANIFEST_DIR")).join("tests/fixtures/canvas-paint");
    // Alpha bytes extracted from the independently captured real monitor PNGs
    // (corners.reference.json), not generated by the mask implementation.
    for (name,vertical,expected) in [
        ("corner-vector-horizontal",false,[177,49,133,37,177,255,255,49]),
        ("corner-overlap-horizontal",false,[145,45,114,34,145,190,190,45]),
        ("corner-vector-vertical",true,[128,64,64,32,128,255,255,64]),
        ("corner-overlap-vertical",true,[110,60,60,31,110,190,190,60]),
    ] {
        let prepared = styk_eval::prepare(styk_eval::open(&at.join(format!("{name}.json"))).unwrap());
        let assets = Assets::build(&prepared.doc);
        let scene = geometry::build(&prepared.doc, &prepared.evaluate(0.0));
        let list = drawlist::encode(&prepared.doc, &assets, &scene);
        let [w,h] = prepared.doc.canvas.map(|v|v as f64);
        let css_zoom = (278.0/w).min(139.0/h);
        let zoom = css_zoom*1.25;
        let pan = [(278.0-w*css_zoom)/2.0*1.25,(139.0-h*css_zoom)/2.0*1.25];
        let view = ViewParams { matrix: [zoom,0.0,0.0,zoom,pan[0],pan[1]], artboard: [pan[0],pan[1],pan[0]+w*zoom,pan[1]+h*zoom], clip_to_artboard: true,
            clear: [0.0;4], zoom, pan, stretch: 1.0, camera_view: true, camera_limit: f64::INFINITY };
        let mut raster = Raster::new(Edges::Smooth);
        let native = raster.render(&list, &Images::default(), &view, [348,174]).straight();
        raster.set_paint_context(PaintContext::CanvasDirect { background_bounds:[0.0,0.0,w,h] });
        let image = raster.render(&list, &Images::default(), &view, [348,174]).straight();
        let points = if vertical {[[0,32],[347,32],[0,141],[347,141],[139,32],[139,33],[139,140],[139,141]]}
            else {[[19,0],[328,0],[19,173],[328,173],[19,87],[20,87],[327,87],[328,87]]};
        for ([x,y],alpha) in points.into_iter().zip(expected) {
            let actual = &image[(y*348+x)*4..(y*348+x+1)*4];
            assert_eq!(actual[3],alpha,"{name} at{x},{y}: actual Canvas paint alpha");
        }
        raster.set_paint_context(PaintContext::Native);
        assert_eq!(raster.render(&list,&Images::default(),&view,[348,174]).straight(),native,"explicit Native reset preserves the shared renderer's original paint policy");
        assert_ne!(image,native,"recorded fractional Canvas clip must not become a blanket Native policy");
    }
}
