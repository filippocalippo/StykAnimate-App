//! `cargo xtask design generate|check`: the design system's generated sources.
//!
//! - `styk-design/src/tokens.rs` from `src/styles/tokens.css` ([`crate::tokens`]);
//! - `styk-design/icons/*.svg` and `styk-design/src/icon_table.rs` from `src/icons.mjs` (Node evaluates the module through
//!   `export-icons.mjs`, so the icons are exactly the interface's own).
//!
//! `check` regenerates everything in memory and fails on any difference, missing file or stray icon file.

use crate::tokens;
use std::collections::BTreeMap;
use std::path::{Path, PathBuf};
use std::process::Command;

/// Everything generated, by path relative to the repository root.
pub type Files = BTreeMap<PathBuf, String>;

const TOKENS_CSS: &str = "src/styles/tokens.css";
const DESIGN: &str = "engine/crates/styk-design";

pub fn generate_files(root: &Path) -> Result<Files, String> {
    let mut files = Files::new();
    let css = std::fs::read_to_string(root.join(TOKENS_CSS)).map_err(|e| format!("{TOKENS_CSS}: {e}"))?;
    files.insert(Path::new(DESIGN).join("src/tokens.rs"), tokens::generate(&css)?);
    let listing = node_icons(root)?;
    let (svgs, rust) = icons(&listing)?;
    for (name, svg) in svgs {
        files.insert(Path::new(DESIGN).join("icons").join(format!("{name}.svg")), svg);
    }
    files.insert(Path::new(DESIGN).join("src/icon_table.rs"), rust);
    Ok(files)
}

fn node_icons(root: &Path) -> Result<String, String> {
    let script = root.join("engine/crates/xtask/export-icons.mjs");
    let output = Command::new("node").arg(&script).output().map_err(|e| format!("could not run node ({e}): the icons come from src/icons.mjs, which Node evaluates"))?;
    if !output.status.success() {
        return Err(format!("export-icons.mjs failed:\n{}", String::from_utf8_lossy(&output.stderr)));
    }
    String::from_utf8(output.stdout).map_err(|e| e.to_string())
}

/// The svg of every shape, and `icon_table.rs`, from `export-icons.mjs`'s listing.
pub fn icons(listing: &str) -> Result<(BTreeMap<String, String>, String), String> {
    let mut shapes = BTreeMap::new();
    let mut aliases = BTreeMap::new();
    for line in listing.lines() {
        let mut parts = line.splitn(3, ' ');
        match (parts.next(), parts.next(), parts.next()) {
            (Some("shape"), Some(name), Some(svg)) => {
                if !name.chars().all(|c| c.is_ascii_alphanumeric() || c == '-') {
                    return Err(format!("icon name {name:?} is not usable as a file name"));
                }
                shapes.insert(name.to_string(), format!("{svg}\n"));
            }
            (Some("alias"), Some(alias), Some(target)) => {
                aliases.insert(alias.to_string(), target.to_string());
            }
            _ => return Err(format!("unexpected icon listing line {line:?}")),
        }
    }
    if let Some((alias, target)) = aliases.iter().find(|(alias, target)| !shapes.contains_key(*target) || shapes.contains_key(*alias)) {
        return Err(format!("alias {alias} -> {target} is not a different name for a shape"));
    }
    let mut rust = String::from(
        "// @generated by `cargo xtask design generate` from src/icons.mjs. Do not edit: change the source and regenerate.\n// `cargo xtask design check` fails when this file or an icon file is stale.\n\n",
    );
    rust.push_str("/// The shape names of the interface's icon set, sorted.\npub const NAMES: &[&str] = &[\n");
    for name in shapes.keys() {
        rust.push_str(&format!("    {name:?},\n"));
    }
    rust.push_str("];\n\n/// Every shape's SVG, by name, sorted. Colour is black; tint when drawing.\npub(crate) static SHAPES: &[(&str, &[u8])] = &[\n");
    for name in shapes.keys() {
        rust.push_str(&format!("    ({name:?}, include_bytes!(\"../icons/{name}.svg\")),\n"));
    }
    rust.push_str("];\n\n/// The other names the interface uses for a shape, sorted: `(alias, shape)`.\npub(crate) static ALIASES: &[(&str, &str)] = &[\n");
    for (alias, target) in &aliases {
        rust.push_str(&format!("    ({alias:?}, {target:?}),\n"));
    }
    rust.push_str("];\n");
    Ok((shapes, rust))
}

pub fn generate(root: &Path) -> Result<(), String> {
    let files = generate_files(root)?;
    let icons_dir = root.join(DESIGN).join("icons");
    std::fs::create_dir_all(&icons_dir).map_err(|e| e.to_string())?;
    for stray in stray_icons(root, &files)? {
        std::fs::remove_file(&stray).map_err(|e| format!("{}: {e}", stray.display()))?;
    }
    let mut written = 0;
    for (path, content) in &files {
        let full = root.join(path);
        if std::fs::read_to_string(&full).ok().as_deref() != Some(content) {
            std::fs::write(&full, content).map_err(|e| format!("{}: {e}", full.display()))?;
            written += 1;
        }
    }
    println!("design: {} generated files, {written} written", files.len());
    Ok(())
}

pub fn check(root: &Path) -> Result<(), String> {
    let files = generate_files(root)?;
    let mut problems = Vec::new();
    for (path, content) in &files {
        match std::fs::read_to_string(root.join(path)) {
            Ok(found) if found == *content => {}
            Ok(_) => problems.push(format!("stale: {}", path.display())),
            Err(_) => problems.push(format!("missing: {}", path.display())),
        }
    }
    for stray in stray_icons(root, &files)? {
        problems.push(format!("stray: {}", stray.strip_prefix(root).unwrap_or(&stray).display()));
    }
    if problems.is_empty() {
        println!("design: {} generated files are current", files.len());
        Ok(())
    } else {
        Err(format!("{}\nrun `cargo xtask design generate`", problems.join("\n")))
    }
}

/// Icon files that no icon in the source accounts for.
fn stray_icons(root: &Path, files: &Files) -> Result<Vec<PathBuf>, String> {
    let dir = root.join(DESIGN).join("icons");
    let Ok(entries) = std::fs::read_dir(&dir) else { return Ok(Vec::new()) };
    let mut strays = Vec::new();
    for entry in entries {
        let path = entry.map_err(|e| e.to_string())?.path();
        let relative = Path::new(DESIGN).join("icons").join(path.file_name().unwrap_or_default());
        if !files.contains_key(&relative) {
            strays.push(path);
        }
    }
    Ok(strays)
}

#[cfg(test)]
mod tests {
    use super::*;

    const LISTING: &str = "shape file <svg a=\"1\"><path d=\"M0\"/></svg>\nshape close <svg><path d=\"M1\"/></svg>\nalias x close\n";

    #[test]
    fn shapes_become_files_and_a_sorted_table() {
        let (svgs, rust) = icons(LISTING).unwrap();
        assert_eq!(svgs.keys().map(String::as_str).collect::<Vec<_>>(), ["close", "file"]);
        assert_eq!(svgs["file"], "<svg a=\"1\"><path d=\"M0\"/></svg>\n");
        assert!(rust.contains("(\"close\", include_bytes!(\"../icons/close.svg\")),\n    (\"file\", include_bytes!(\"../icons/file.svg\")),"));
        assert!(rust.contains("(\"x\", \"close\"),"));
    }

    #[test]
    fn an_alias_must_point_at_a_shape_and_not_shadow_one() {
        assert!(icons("shape a <svg/>\nalias b missing\n").is_err());
        assert!(icons("shape a <svg/>\nshape b <svg/>\nalias b a\n").is_err());
        assert!(icons("shape ../a <svg/>\n").is_err());
        assert!(icons("nonsense\n").is_err());
    }
}
