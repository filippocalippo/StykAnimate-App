//! Generate the owner API inventory and enforce the tools' import boundary.
use std::{fs, path::Path};
const SOURCES: &[(&str, &str)] = &[
    ("styk-trace", "ring.rs"),
    ("styk-trace", "clock.rs"),
    ("styk-engine", "inspect.rs"),
    ("styk-edit", "inspect.rs"),
    ("styk-eval", "inspect.rs"),
    ("styk-render", "inspect.rs"),
    ("styk-core", "inspect.rs"),
];
fn generated(root: &Path) -> Result<String, String> {
    let mut out="# Generated by cargo xtask read-apis. Do not edit by hand.\nformat = \"styk-read-apis/1\"\n".to_owned();
    for (owner, file) in SOURCES {
        let source = format!("engine/crates/{owner}/src/{file}");
        let text = fs::read_to_string(root.join(&source)).map_err(|e| e.to_string())?;
        let mut names: Vec<_> = text
            .split("pub fn ")
            .skip(1)
            .map(|s| {
                s.split(|c: char| !c.is_ascii_alphanumeric() && c != '_')
                    .next()
                    .unwrap_or("")
            })
            .collect();
        names.sort_unstable();
        names.dedup();
        out.push_str(&format!(
            "\n[[owner]]\ncrate = \"{owner}\"\nsource = \"{source}\"\nitems = [{}]\n",
            names
                .iter()
                .map(|s| format!("\"{s}\""))
                .collect::<Vec<_>>()
                .join(", ")
        ));
    }
    Ok(out)
}
fn imports(path: &Path) -> Result<(), String> {
    for entry in fs::read_dir(path).map_err(|e| e.to_string())? {
        let path = entry.map_err(|e| e.to_string())?.path();
        if path.is_dir() {
            imports(&path)?;
        } else if path.extension().is_some_and(|s| s == "rs") {
            let text = fs::read_to_string(&path).map_err(|e| e.to_string())?;
            for owner in [
                "styk_core",
                "styk_engine",
                "styk_edit",
                "styk_eval",
                "styk_render",
            ] {
                for suffix in text.split(&format!("{owner}::")).skip(1) {
                    let module = suffix
                        .split(|c: char| !c.is_ascii_alphanumeric() && c != '_')
                        .next()
                        .unwrap_or("");
                    let existing_pen = path.components().any(|p| p.as_os_str() == "pen_lab")
                        && owner == "styk_core"
                        && ["drawing", "services"].contains(&module);
                    let automation = owner == "styk_core" && module == "automation";
                    // Plain developer messages and presentation labels, not engine access.
                    let panel_contract = owner == "styk_core" && ["dev_extension", "i18n"].contains(&module);
                    if module != "inspect" && !existing_pen && !automation && !panel_contract {
                        return Err(format!(
                            "{}: tools may import {owner} only through its inspect or core automation API",
                            path.display()
                        ));
                    }
                }
            }
        }
    }
    Ok(())
}
pub fn run(root: &Path, check: bool) -> Result<(), String> {
    let text = generated(root)?;
    let path = root.join("docs/native/devtools-read-apis.toml");
    if check {
        if fs::read_to_string(&path).ok().as_deref() != Some(&text) {
            return Err("owner API inventory is stale; cargo xtask read-apis".into());
        }
    } else {
        fs::write(path, text).map_err(|e| e.to_string())?;
    }
    imports(&root.join("engine/crates/styk-devtools/src"))?;
    imports(&root.join("engine/crates/styk-devtools-engine/src"))?;
    println!(
        "inspection APIs: inventory current; tools use owner inspection and core automation APIs (existing pen lab exception)"
    );
    Ok(())
}
