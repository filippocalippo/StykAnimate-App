//! Builds the English message catalogue (`styk_core::i18n`) from the interface's own generated catalogue,
//! `src/locales/en.mjs` (whose body is one JSON object), so the native interface shows exactly today's English text and
//! never keeps a copy that drifts. Plain messages and plural messages (`{"one": ..., "other": ...}`) are kept; the table
//! is sorted by key for a binary search.

use std::fmt::Write as _;
use std::path::PathBuf;

fn main() {
    let manifest = PathBuf::from(std::env::var_os("CARGO_MANIFEST_DIR").unwrap_or_default());
    let source = manifest.join("../../../src/locales/en.mjs");
    println!("cargo:rerun-if-changed={}", source.display());
    let text = match std::fs::read_to_string(&source) {
        Ok(text) => text,
        Err(error) => panic!("the English catalogue {} cannot be read: {error}", source.display()),
    };
    let start = text.find('{').unwrap_or_else(|| panic!("{} holds no object", source.display()));
    let mut parser = Parser { bytes: text.as_bytes(), at: start };
    let mut entries = parser.catalogue();
    entries.sort_by(|a, b| a.0.cmp(&b.0));
    entries.dedup_by(|a, b| a.0 == b.0);
    let mut out = String::from("// Generated by build.rs from src/locales/en.mjs. Do not edit.\n");
    out.push_str("pub(crate) static ENGLISH: &[(&str, Entry)] = &[\n");
    for (key, entry) in &entries {
        match entry {
            Value::Plain(message) => writeln!(out, "    ({key:?}, Entry::Plain({message:?})),").unwrap_or(()),
            Value::Plural(forms) => {
                let forms: Vec<String> = forms.iter().map(|(category, message)| format!("({category:?}, {message:?})")).collect();
                writeln!(out, "    ({key:?}, Entry::Plural(&[{}])),", forms.join(", ")).unwrap_or(())
            }
        }
    }
    out.push_str("];\n");
    let target = PathBuf::from(std::env::var_os("OUT_DIR").unwrap_or_default()).join("english.rs");
    if let Err(error) = std::fs::write(&target, out) {
        panic!("{} cannot be written: {error}", target.display());
    }
}

enum Value {
    Plain(String),
    Plural(Vec<(String, String)>),
}

/// The subset of JSON the catalogue uses: an object of strings and objects of strings.
struct Parser<'a> {
    bytes: &'a [u8],
    at: usize,
}

impl Parser<'_> {
    fn fail(&self, what: &str) -> ! {
        panic!("src/locales/en.mjs: {what} at byte {}", self.at)
    }

    fn space(&mut self) {
        while self.at < self.bytes.len() && self.bytes[self.at].is_ascii_whitespace() {
            self.at += 1;
        }
    }

    fn expect(&mut self, byte: u8) {
        self.space();
        if self.bytes.get(self.at) != Some(&byte) {
            self.fail(&format!("expected `{}`", byte as char));
        }
        self.at += 1;
    }

    fn peek(&mut self) -> u8 {
        self.space();
        self.bytes.get(self.at).copied().unwrap_or(0)
    }

    fn string(&mut self) -> String {
        self.expect(b'"');
        let mut out = Vec::new();
        loop {
            let Some(&byte) = self.bytes.get(self.at) else { self.fail("unterminated string") };
            self.at += 1;
            match byte {
                b'"' => break,
                b'\\' => {
                    let Some(&escape) = self.bytes.get(self.at) else { self.fail("unterminated escape") };
                    self.at += 1;
                    let decoded = match escape {
                        b'n' => '\n',
                        b't' => '\t',
                        b'r' => '\r',
                        b'b' => '\u{8}',
                        b'f' => '\u{c}',
                        b'/' => '/',
                        b'\\' => '\\',
                        b'"' => '"',
                        b'u' => {
                            let unit = self.hex4();
                            let scalar = if (0xd800..0xdc00).contains(&unit) {
                                if self.bytes.get(self.at..self.at + 2) != Some(b"\\u") {
                                    self.fail("lone high surrogate");
                                }
                                self.at += 2;
                                let low = self.hex4();
                                0x10000 + ((unit - 0xd800) << 10) + (low - 0xdc00)
                            } else {
                                unit
                            };
                            char::from_u32(scalar).unwrap_or_else(|| self.fail("invalid escape"))
                        }
                        _ => self.fail("unknown escape"),
                    };
                    let mut buffer = [0; 4];
                    out.extend_from_slice(decoded.encode_utf8(&mut buffer).as_bytes());
                }
                _ => out.push(byte),
            }
        }
        String::from_utf8(out).unwrap_or_else(|_| self.fail("invalid UTF-8"))
    }

    fn hex4(&mut self) -> u32 {
        let digits = self.bytes.get(self.at..self.at + 4).unwrap_or_else(|| self.fail("short escape"));
        let digits = std::str::from_utf8(digits).unwrap_or_else(|_| self.fail("bad escape"));
        self.at += 4;
        u32::from_str_radix(digits, 16).unwrap_or_else(|_| self.fail("bad escape"))
    }

    fn catalogue(&mut self) -> Vec<(String, Value)> {
        let mut entries = Vec::new();
        self.expect(b'{');
        while self.peek() != b'}' {
            let key = self.string();
            self.expect(b':');
            let value = if self.peek() == b'{' {
                let mut forms = Vec::new();
                self.expect(b'{');
                while self.peek() != b'}' {
                    let category = self.string();
                    self.expect(b':');
                    forms.push((category, self.string()));
                    if self.peek() == b',' {
                        self.at += 1;
                    }
                }
                self.expect(b'}');
                Value::Plural(forms)
            } else {
                Value::Plain(self.string())
            };
            entries.push((key, value));
            if self.peek() == b',' {
                self.at += 1;
            }
        }
        self.expect(b'}');
        entries
    }
}
