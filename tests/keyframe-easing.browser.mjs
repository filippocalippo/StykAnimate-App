import {chromium} from 'playwright';
import assert from 'node:assert/strict';
import {mkdir} from 'node:fs/promises';
import {createRequire} from 'node:module';
import {fileURLToPath} from 'node:url';
const {startBackend}=createRequire(import.meta.url)('../desktop/backend.cjs');
const backend=await startBackend({appRoot:fileURLToPath(new URL('..',import.meta.url))});
const browser = await chromium.launch({channel:'chrome',headless:true});
const page = await browser.newPage({viewport:{width:1500,height:950}}), errors=[];
page.on('pageerror', error=>errors.push(error.message));
await mkdir('artifacts/easing',{recursive:true});
const settle=()=>page.evaluate(()=>new Promise(resolve=>requestAnimationFrame(()=>requestAnimationFrame(resolve))));
try {
  await page.goto(backend.origin); await page.waitForFunction(()=>window.styk?.ready);
  await page.evaluate(async()=>{
    const {emptyDocument,createFrame,createObject}=await import('/src/demo.mjs');
    const report=emptyDocument(); report.canvas_width=640;report.canvas_height=400;
    report.keyframes=[100,300,160].map(x=>createFrame([createObject(report.figure_types[0],1,x,200),createObject(report.figure_types[0],2,x+160,200)],20));
    styk.editor.load(report);styk.editor.select(1);styk.timeline.setZoom(14);
  });
  await settle();
  const point=()=>page.evaluate(()=>{
    const t=styk.timeline,r=t.scroll.getBoundingClientRect(),row=t.tracks.findIndex(track=>track.target?.kind==='figure'&&track.target.uid===1&&track.property==='pose');
    if(row<0)throw new Error('Missing pose row: '+JSON.stringify(t.tracks.map(x=>[x.id,x.property])));
    return {x:r.left+12+.5*t.pxPerTick-t._offsetX(),y:r.top+31+row*30+15-t._offsetY()};
  });
  const p=await point();await page.mouse.dblclick(p.x,p.y);await page.getByRole('dialog',{name:'Keyframe easing'}).waitFor();
  assert.equal(await page.evaluate(()=>document.querySelector(':modal')),null);
  const bounds=await page.getByRole('dialog',{name:'Keyframe easing'}).boundingBox();
  assert.ok(bounds.width<250 && bounds.y+bounds.height<p.y && Math.abs(bounds.x+bounds.width/2-p.x)<1);
  await page.screenshot({path:'artifacts/easing/compact-popover.png'});
  assert.deepEqual(await page.getByRole('radio').allTextContents(),['Auto','Bezier','Ease in','Ease out','Linear','Constant']);
  await page.getByRole('radio',{name:'Bezier',exact:true}).click();
  await page.getByLabel('Control 1 · X',{exact:true}).fill('0.15');
  await page.getByLabel('Control 1 · Y',{exact:true}).fill('0.8');
  await page.screenshot({path:'artifacts/easing/bezier-popover.png'});
  await page.getByRole('button',{name:'Apply',exact:true}).click();await settle();
  let values=await page.evaluate(()=>{styk.editor.seek(5);return styk.editor.evaluatedFrame.objects.map(o=>[o.unique_id,o.root_x]);});
  assert.equal(values.find(([id])=>id===2)[1],310);assert.ok(values.find(([id])=>id===1)[1]>150);
  await page.evaluate(()=>styk.editor.undo());await settle();
  assert.equal(await page.evaluate(()=>styk.editor.animationChannels.length),0);
  await page.evaluate(()=>styk.editor.redo());await settle();
  await page.mouse.dblclick(p.x,p.y);await page.getByRole('dialog',{name:'Keyframe easing'}).waitFor();
  assert.equal(await page.getByLabel('Control 1 · X',{exact:true}).inputValue(),'0.15');
  const handle=await page.locator('[data-handle="0"]').boundingBox();
  await page.mouse.move(handle.x+handle.width/2,handle.y+handle.height/2);await page.mouse.down();
  await page.mouse.move(handle.x+handle.width/2+12,handle.y+handle.height/2-8,{steps:4});await page.mouse.up();
  assert.notEqual(await page.getByLabel('Control 1 · X',{exact:true}).inputValue(),'0.15');
  await page.getByLabel('Control 1 · X',{exact:true}).fill('1.5');
  assert.equal(await page.getByRole('button',{name:'Apply',exact:true}).isDisabled(),true);
  await page.keyboard.press('Escape');
  await page.mouse.dblclick(p.x,p.y);await page.getByRole('dialog',{name:'Keyframe easing'}).waitFor();
  assert.equal(await page.getByLabel('Control 1 · X',{exact:true}).inputValue(),'0.15');
  const history=await page.evaluate(()=>styk.editor._undo.length);
  await page.mouse.click(1400,150);await settle();
  assert.equal(await page.locator('.styk-easing-popover').count(),0);
  assert.equal(await page.evaluate(()=>styk.editor._undo.length),history);
  await page.mouse.dblclick(p.x,p.y);await page.getByRole('dialog',{name:'Keyframe easing'}).waitFor();
  await page.getByRole('radio',{name:'Constant',exact:true}).click();
  assert.equal(await page.evaluate(()=>{styk.editor.seek(19);return styk.editor.evaluatedFrame.objects.find(o=>o.unique_id===1).root_x;}),100);
  assert.equal(await page.evaluate(()=>{styk.editor.seek(20);return styk.editor.evaluatedFrame.objects.find(o=>o.unique_id===1).root_x;}),300);
  await page.mouse.dblclick(p.x,p.y);await page.getByRole('dialog',{name:'Keyframe easing'}).waitFor();
  await page.getByRole('radio',{name:'Auto',exact:true}).click();
  assert.equal(await page.evaluate(()=>{styk.editor.seek(5);return styk.editor.evaluatedFrame.objects.find(o=>o.unique_id===1).root_x;}),131.25);
  await page.evaluate(()=>styk.settingsUI.commit({timelineMode:'simple'}));await settle();
  await page.locator('.styk-simple-preview').first().dblclick();await page.getByRole('dialog',{name:'Keyframe easing'}).waitFor();
  await page.screenshot({path:'artifacts/easing/simple-popover.png'});
  await page.getByRole('radio',{name:'Ease out',exact:true}).click();
  assert.equal(await page.evaluate(()=>styk.editor.report.keyframes[0]._styk.easing.interpolation),'ease-out');
  await page.locator('.styk-simple-preview').first().click({button:'right'});
  await page.getByRole('menuitem',{name:'Keyframe easing',exact:true}).click();
  await page.getByRole('radio',{name:'Auto',exact:true}).click();
  assert.equal(await page.evaluate(()=>styk.editor.report.keyframes[0]._styk.easing.interpolation),'auto');
  await settle();
  await page.locator('.styk-simple-preview').first().dblclick();
  await page.getByRole('dialog',{name:'Keyframe easing'}).waitFor();
  await settle();
  assert.equal(await page.getByRole('radio',{name:'Auto',exact:true}).getAttribute('aria-checked'),'true');
  await page.screenshot({path:'artifacts/easing/simple-auto-popover.png'});
  assert.equal(await page.locator('#easing').count(),0);
  assert.deepEqual(errors,[]);console.log('PASS: anchored nonmodal figure popover, six modes, Auto in both timelines, custom curve, independent motion, undo/redo, persistence, constant boundary, simple context menu, removed global toggle');
} finally {await browser.close();backend.stop();}
