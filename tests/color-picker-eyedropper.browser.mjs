import assert from 'node:assert/strict';
import {mkdir} from 'node:fs/promises';
import {chromium} from './support/playwright.mjs';

await mkdir('artifacts/color-picker',{recursive:true});
const browser=await chromium.launch({channel:'chrome',headless:true,args:['--enable-unsafe-webgpu']});
try {
  for(const backend of ['gpu','canvas']) {
    const page=await browser.newPage({viewport:{width:1440,height:1000},deviceScaleFactor:1.5}),errors=[];
    page.setDefaultTimeout(15000);
    page.on('pageerror',error=>errors.push(error.message));
    if(backend==='canvas')await page.addInitScript(()=>Object.defineProperty(navigator,'gpu',{value:undefined}));
    await page.goto(process.env.STYK_URL || 'http://127.0.0.1:47831');
    await page.waitForFunction(()=>window.styk?.ready);
    await page.evaluate(async()=>{
      const {emptyDocument,createFrame,createObject}=await import('/src/demo.mjs');
      const report=emptyDocument(),a=report.figure_types[0];
      a.segments=a.segments.slice(0,1);a.segments[0].length=140;a.segments[0].angle_rad=0;a.segments[0].thickness=45;
      const b=structuredClone(a);b.figure_type_id=2;b.segments[0].color_rgb=[36,168,112];
      report.figure_types.push(b);report.keyframes=[createFrame([createObject(a,1,170,350),createObject(b,2,420,260)])];
      styk.editor.load(report);styk.editor.select(1,0);styk.fit();
      window.readSelectedPaint=async()=>{
        const {resolveInstanceFigure}=await import('/src/animation-style.mjs');
        const {segmentPaint}=await import('/src/paint.mjs');
        return segmentPaint(resolveInstanceFigure(styk.editor.figure,styk.editor.object).segments[0]);
      };
    });
    await page.waitForFunction(()=>!styk.state.dirtyRender);
    await page.evaluate(()=>new Promise(resolve=>requestAnimationFrame(()=>requestAnimationFrame(resolve))));
    const point=await page.evaluate(()=>{const r=document.querySelector('#overlay').getBoundingClientRect(),v=styk.state.view;return {x:r.left+v.x+470*v.scale,y:r.top+v.y+260*v.scale};});
    if(await page.locator('[data-property-scope="joint"]').count())await page.locator('[data-property-scope="joint"]').click();
    await page.locator('#segment-color').click();
    const eyedropper=page.getByRole('button',{name:'Eyedropper',exact:true});
    const originalPaint=await page.evaluate(()=>readSelectedPaint());
    assert.equal(await eyedropper.getAttribute('aria-pressed'),'false');
    await page.mouse.move(point.x,point.y);
    assert.equal(await page.locator('.paint-eyedropper').count(),0);
    assert.equal(await page.locator('.paint-magnifier:popover-open').count(),0);
    await page.screenshot({path:`artifacts/color-picker/idle-${backend}.png`});
    await page.mouse.click(point.x,point.y);
    assert.equal(await page.locator('.paint-picker').count(),0,'Canvas click dismisses the inactive picker');
    await page.evaluate(()=>styk.editor.select(1,0));
    assert.deepEqual(await page.evaluate(()=>readSelectedPaint()),originalPaint,'Dismissal does not sample a color');
    await page.locator('#segment-color').click();
    await eyedropper.click();
    assert.equal(await eyedropper.getAttribute('aria-pressed'),'true');
    await eyedropper.click();
    assert.equal(await eyedropper.getAttribute('aria-pressed'),'false');
    await page.mouse.move(point.x,point.y);
    assert.equal(await page.locator('.paint-eyedropper').count(),0);
    assert.equal(await page.locator('.paint-magnifier:popover-open').count(),0);
    await page.mouse.click(point.x,point.y);
    assert.equal(await page.locator('.paint-picker').count(),0,'Turning off the eyedropper restores click-away dismissal');
    await page.evaluate(()=>styk.editor.select(1,0));
    await page.locator('#segment-color').click();
    await eyedropper.click();
    const hex=page.getByRole('textbox',{name:'Hex color'});
    await page.getByRole('spinbutton',{name:'Alpha percent',exact:true}).fill('60');
    await page.getByRole('spinbutton',{name:'Alpha percent',exact:true}).press('Tab');
    const before=await page.evaluate(()=>readSelectedPaint());
    const revision=await page.evaluate(()=>styk.editor.revision);
    await page.mouse.move(point.x,point.y);
    assert.match(await page.locator('#overlay').evaluate(el=>getComputedStyle(el).cursor),/svg\+xml/);
    await page.waitForFunction(()=>document.querySelector('.paint-magnifier:popover-open code')?.textContent==='#24A870');
    assert.equal(await page.evaluate(()=>styk.editor.revision),revision,'Hover does not edit the document');
    assert.deepEqual(await page.locator('.paint-magnifier canvas').evaluate(el=>Array.from(el.getContext('2d').getImageData(5,5,1,1).data)),[36,168,112,255]);
    assert.equal(await page.locator('.paint-magnifier').evaluate(el=>getComputedStyle(el).pointerEvents),'none');
    await page.screenshot({path:`artifacts/color-picker/magnifier-${backend}.png`});
    const edge=await page.evaluate(()=>{const r=document.querySelector('#overlay').getBoundingClientRect(),v=styk.state.view;return {x:r.left+v.x+470*v.scale,y:r.top+v.y+237.5*v.scale};});
    await page.mouse.move(edge.x,edge.y);
    await page.waitForFunction(()=>{
      const c=document.querySelector('.paint-magnifier canvas'),d=c.getContext('2d').getImageData(0,0,11,11).data;
      return d.some((value,index)=>index%4===0&&value===255)&&d.some((value,index)=>index%4===0&&value===36);
    });
    await page.screenshot({path:`artifacts/color-picker/magnifier-edge-${backend}.png`});
    await page.waitForTimeout(150);
    const idleDraws=await page.evaluate(()=>styk.state.drawCalls);
    await page.waitForTimeout(150);
    assert.equal(await page.evaluate(()=>styk.state.drawCalls),idleDraws,'Idle loupe does not keep rendering');
    await hex.hover();
    assert.equal(await page.locator('.paint-magnifier:popover-open').count(),0,'Returning to the picker hides the loupe');
    await page.mouse.move(point.x,point.y);
    await page.waitForFunction(()=>document.querySelector('.paint-magnifier:popover-open code')?.textContent==='#24A870');
    await page.waitForTimeout(150); // Sample an idle WebGPU surface after presentation.
    await page.mouse.click(point.x,point.y);
    await page.waitForFunction(()=>document.querySelector('[data-hex]')?.value==='24A870');
    assert.equal(await page.locator('.paint-picker').count(),1);
    assert.equal(await page.evaluate(()=>styk.editor.selectedUid),1);
    const sampled=await page.evaluate(()=>readSelectedPaint());
    assert.deepEqual(sampled.stops[0].color,[36,168,112]);
    assert.equal(sampled.stops[0].opacity,.6);
    await page.screenshot({path:`artifacts/color-picker/eyedropper-${backend}.png`});
    await page.keyboard.press('Escape');
    assert.equal(await page.locator('.paint-eyedropper').count(),0);
    assert.equal(await page.locator('.paint-magnifier').count(),0);
    await page.evaluate(()=>styk.editor.undo());
    assert.deepEqual(await page.evaluate(()=>readSelectedPaint()),before,'One undo restores the previous color');

    await page.locator('#segment-color').click();
    await page.locator('[data-mode="gradient"]').click();
    await page.getByRole('button',{name:'Add gradient stop',exact:true}).click();
    const gradientBefore=await page.evaluate(()=>readSelectedPaint());
    assert.equal(await eyedropper.getAttribute('aria-pressed'),'false','Reopening resets sampling');
    await eyedropper.click();
    await page.mouse.click(point.x,point.y);
    await page.waitForFunction(()=>document.querySelector('[data-hex]')?.value==='24A870');
    const gradientAfter=await page.evaluate(()=>readSelectedPaint());
    assert.equal(gradientAfter.type,'linear');
    assert.deepEqual(gradientAfter.stops[0],gradientBefore.stops[0]);
    assert.deepEqual(gradientAfter.stops[2],gradientBefore.stops[2]);
    assert.deepEqual(gradientAfter.stops[1].color,[36,168,112]);
    assert.equal(gradientAfter.stops[1].opacity,gradientBefore.stops[1].opacity);
    const root=await page.evaluate(()=>{const r=document.querySelector('#overlay').getBoundingClientRect(),v=styk.state.view;return {x:r.left+v.x+420*v.scale,y:r.top+v.y+260*v.scale};});
    await hex.fill('FF0000');await hex.press('Tab');
    await page.mouse.click(root.x,root.y);
    await page.waitForFunction(()=>document.querySelector('[data-hex]')?.value==='24A870');
    assert.equal(await page.evaluate(()=>styk.editor.selectedUid),1,'Sampling a joint reads artwork and preserves selection');
    const white=await page.evaluate(()=>{const r=document.querySelector('#overlay').getBoundingClientRect(),v=styk.state.view;return {x:r.left+v.x+100*v.scale,y:r.top+v.y+100*v.scale};});
    await page.mouse.click(white.x,white.y);
    await page.waitForFunction(()=>document.querySelector('[data-hex]')?.value==='FFFFFF');
    await hex.fill('112233');await hex.press('Tab');
    assert.equal(await hex.inputValue(),'112233','Returning to the picker retains ordinary input');
    await page.keyboard.press('Escape');
    await page.mouse.click(root.x,root.y);
    assert.equal(await page.evaluate(()=>styk.editor.selectedUid),2,'Canvas selection resumes after closing');
    assert.deepEqual(errors,[]);
    console.log(`${backend}: ${await page.evaluate(()=>styk.state.renderer.stats.backend)}; magnifier, idle rendering, solid, gradient stop, opacity, selection, undo and Escape passed`);
    await page.close();
  }
} finally {await browser.close();}
